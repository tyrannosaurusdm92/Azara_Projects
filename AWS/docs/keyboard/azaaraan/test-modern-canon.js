// Modern-specific regression tests: node docs/keyboard/azaaraan/test-modern-canon.js
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'../../..');
const source=fs.readFileSync(path.join(root,'script/js/keyboard/modern-canon.js'),'utf8');
const context={window:{}};vm.runInNewContext(source,context);
const M=context.window.AZA_MODERN;
const keyOrder='ABDEGHIJKLMNOPRSTWYZ';
assert.equal(M.workingAlphabet,keyOrder);
assert.equal(new Set(keyOrder).size,20);
assert.equal(M.marks.length,12);
assert.equal(M.sounds.length,77);
assert(!M.independentLetters.U);
assert(!M.independentLetters.F);
assert(!M.independentLetters.V);
assert(M.independentLetters.W);
assert(M.independentLetters.P);
const validate=(base,marks,subs=[])=>M.tryEncode(base,marks,subs);
for(const s of M.sounds){
  assert(M.independentLetters[s.base],'no Modern host '+s.id);
  assert(s.marks.length<=2,s.id+' exceeds two diacritics');
  const got=validate(s.base,s.marks);
  assert(got.value,s.id+' failed '+got.error);
  assert.equal(got.ipa,'/'+s.ipa+'/',s.id+' wrong IPA');
}
assert.equal(validate('T',['open','hard']).ipa,'/tæz/');
assert.equal(validate('B',['soft']).ipa,'/v/');
assert.equal(validate('B',['soft','unvoiced']).ipa,'/f/');
assert.equal(validate('P',[]).ipa,'/p/');
assert(!validate('U',[]).value);
assert(!validate('F',[]).value);
assert(!validate('B',['unvoiced']).ipa?.includes('/p/'));
assert.equal(validate('K',['glide']).ipa,'/kw/');
assert.equal(validate('K',['glide','hard']).ipa,'/kʷʰ/');
assert.equal(validate('T',['soft','voiced']).ipa,'/ð/');
assert.equal(validate('T',['soft','unvoiced']).ipa,'/θ/');
assert(!validate('T',['voiced','unvoiced']).value);
assert(!validate('E',['separate']).value);
assert(!validate('B',['separate'],[{base:'E',marks:['open']}]).value);
assert(!validate('E',['open','separate'],[{base:'I',marks:['short','separate']}]).value);
assert(validate('E',['open','separate'],[{base:'I',marks:['short']}]).value);
assert(!validate('T',['open','hard','glide']).value);
assert(validate('T',['open','hard','S01','S02']).value,'punctuation should not consume phonetic mark slots');
assert(validate('T',[],[{base:'E',marks:['open']},{base:'N'}]).value);
assert(!validate('T',[],[{base:'E'},{base:'N'},{base:'S'}]).value);
const crypto=require('node:crypto');
const font=fs.readFileSync(path.join(root,'assets/keyboard/ttf/Azaaraan-Modern-2026.woff2'));
assert.equal(font.length,13056,'Modern font byte count drifted');
assert.equal(crypto.createHash('sha1').update(Buffer.concat([Buffer.from('blob '+font.length+'\0'),font])).digest('hex'),'67fd2545bc39923269e3eb61f2aade72f3fab422');
const css=fs.readFileSync(path.join(root,'style/keyboard/aza-merge.css'),'utf8');
assert(css.includes('Azaaraan-Modern-2026.woff2'));
assert(css.includes('Azaaraan-Archaic.ttf')&&css.includes('Azaaraan-Classical.ttf')&&css.includes('Azaaraan-Traditional.ttf'));
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(html.indexOf('modern-canon.js')>=0);
assert(html.indexOf('modern-canon.js') < html.indexOf('azaaraan-bridge.js'));
const inline=html.match(/<script id="letterData" type="application\/json">([\s\S]*?)<\/script>/);
assert(inline,'inline chart missing');
const chart=JSON.parse(inline[1]);
assert.equal(chart.families.length,20);
assert(!chart.families.some(f=>f.family==='U'));
assert.equal(chart.families.find(f=>f.family==='T').readings.find(x=>x.name.toLowerCase().includes('taz')).ipa,'/tæz/');
assert(chart.roots.find(x=>x.slot===37).stages.traditional,'historical U roots must remain untouched');
assert.equal(chart.roots.find(x=>x.slot===37).stages.modern,null);
console.log('Modern Aza’raan canonical tests passed: 20 hosts, 77 entries, 12 marks, mergers, subscript limits, historical stages.');
